-- 027_tutor_checks_and_flashcards.sql
--
-- Two things that turn talking and revising into evidence the learner model can use.
--
-- 1. 'tutor' as an attempt source. After answering from the course material the tutor may ask
--    one quick check question; the learner's answer is an attempt like any other and moves
--    mastery and the revision schedule. Its own source rather than 'revision', so analysis can
--    tell a one-question check inside a chat from a revision session.
--
-- 2. flashcards: cards written once per topic per learner from that topic's excerpts, each tied
--    to the excerpt it came from so it can cite it. Generated by the backend (an AI call), so
--    learners read their own and write nothing.

alter table public.question_attempts drop constraint if exists question_attempts_source_known;
alter table public.question_attempts add constraint question_attempts_source_known
    check (source in ('practice', 'assessment', 'topic_test', 'mock_test', 'revision', 'tutor'));

create table if not exists public.flashcards (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.profiles (id) on delete cascade,
    -- Cascade: a card is derived from the topic's excerpts and means nothing without the topic.
    topic_id uuid not null references public.topics (id) on delete cascade,
    front text not null,
    back text not null,
    -- Set null rather than cascade: deleting a source should not silently empty a deck mid-revision.
    source_chunk_id uuid references public.source_chunks (id) on delete set null,
    created_at timestamptz not null default now(),
    constraint flashcards_front_not_blank check (char_length(trim(front)) between 1 and 500),
    constraint flashcards_back_not_blank check (char_length(trim(back)) between 1 and 1000)
);

comment on table public.flashcards is
    'Revision cards generated once per (learner, topic) from the topic''s excerpts. Written by the backend only.';

create index if not exists flashcards_user_topic_idx on public.flashcards (user_id, topic_id);

alter table public.flashcards enable row level security;
revoke all on public.flashcards from anon, authenticated;

drop policy if exists "Learners read their own flashcards" on public.flashcards;
create policy "Learners read their own flashcards"
    on public.flashcards for select to authenticated
    using (auth.uid() = user_id);

grant select on public.flashcards to authenticated;
